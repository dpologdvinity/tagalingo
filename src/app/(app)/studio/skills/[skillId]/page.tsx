/** Studio: review one skill's word list and exercises, lesson by lesson. */
import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import { selectGenerator } from "@/lib/content/generators";
import { getSkillForReview, type ReviewExercise } from "@/server/studio";
import { requireReviewer } from "@/server/session";
import { ExercisePreview, typeLabel } from "./exercise-preview";
import { GenerateButton, ReviewControls } from "./review-controls";

export const metadata: Metadata = { title: "Review skill" };

const FILTERS = ["DRAFT", "APPROVED", "REJECTED", "ALL"] as const;
type Filter = (typeof FILTERS)[number];
const FILTER_LABEL: Record<Filter, string> = {
  DRAFT: "Drafts",
  APPROVED: "Approved",
  REJECTED: "Rejected",
  ALL: "All",
};

const STATUS_STYLE = {
  DRAFT: "bg-mango-soft text-mango-deep",
  APPROVED: "bg-lagoon-soft text-lagoon",
  REJECTED: "bg-gumamela-soft text-gumamela",
} as const;

function ExerciseCard({ ex }: { ex: ReviewExercise }) {
  return (
    <li className="space-y-4 rounded-3xl border-2 border-line bg-surface p-5">
      <div className="flex flex-wrap items-center gap-2 text-sm">
        <span className={`rounded-full px-2.5 py-0.5 font-bold ${STATUS_STYLE[ex.status]}`}>
          {ex.status.toLowerCase()}
        </span>
        <span className="font-bold">{typeLabel(ex.type)}</span>
        <span className="text-ink-soft">
          {ex.generatedBy ? `generated by ${ex.generatedBy}` : `source: ${ex.source.toLowerCase()}`}
        </span>
      </div>
      {ex.parsed ? (
        <ExercisePreview ex={ex.parsed} />
      ) : (
        <pre className="overflow-auto text-sm">{JSON.stringify(ex.rawPayload, null, 2)}</pre>
      )}
      {ex.warnings.length > 0 && (
        <ul className="space-y-1 rounded-2xl bg-mango-soft px-4 py-3 text-sm text-ink">
          {ex.warnings.map((w) => (
            <li key={w}>⚠️ {w}</li>
          ))}
        </ul>
      )}
      {ex.reviewNote && (
        <p className="text-sm text-ink-soft">
          Note{ex.reviewedBy ? ` from ${ex.reviewedBy}` : ""}: {ex.reviewNote}
        </p>
      )}
      <ReviewControls exerciseId={ex.id} status={ex.status} payload={ex.rawPayload} />
    </li>
  );
}

export default async function SkillReviewPage({ params, searchParams }: PageProps<"/studio/skills/[skillId]">) {
  await requireReviewer();
  const { skillId } = await params;
  const sp = await searchParams;
  const skill = await getSkillForReview(skillId);
  if (!skill) notFound();

  const all = skill.lessons.flatMap((l) => l.exercises);
  const requested = typeof sp.status === "string" ? (sp.status.toUpperCase() as Filter) : null;
  const filter: Filter =
    requested && FILTERS.includes(requested) ? requested : all.some((e) => e.status === "DRAFT") ? "DRAFT" : "ALL";
  const count = (f: Filter) => (f === "ALL" ? all.length : all.filter((e) => e.status === f).length);

  let generatorName = "the offline stub";
  try {
    if (selectGenerator().provider === "claude") generatorName = "Claude";
  } catch {
    generatorName = "the configured generator";
  }

  return (
    <div className="space-y-6">
      <Link href="/studio" className="font-bold text-lagoon hover:underline">
        Back to studio
      </Link>
      <header>
        <h1 className="font-display text-4xl">
          <span aria-hidden>{skill.emoji} </span>
          {skill.title}
        </h1>
        <p className="text-ink-soft">
          {skill.unit.title}. {skill.description}.
        </p>
      </header>

      <details className="rounded-3xl border-2 border-line bg-surface p-5">
        <summary className="cursor-pointer font-display text-xl">Word list ({skill.words.length} words)</summary>
        <p className="mt-2 text-sm text-ink-soft">
          Edit words in <code>content/tagalog/course.yaml</code>. Generators only use these words.
        </p>
        <ul className="mt-3 divide-y divide-line">
          {skill.words.map((w) => (
            <li key={w.id} className="py-2">
              <strong lang="tl">{w.tagalog}</strong> <span className="text-ink-soft">({w.partOfSpeech})</span> ={" "}
              {w.english}
              {w.exampleTl && (
                <span className="block text-sm text-ink-soft">
                  <span lang="tl">{w.exampleTl}</span> = {w.exampleEn}
                </span>
              )}
              {w.notes && <span className="block text-sm">{w.notes}</span>}
            </li>
          ))}
        </ul>
      </details>

      <nav aria-label="Filter exercises" className="flex flex-wrap gap-2">
        {FILTERS.map((f) => (
          <Link
            key={f}
            href={`/studio/skills/${skill.id}?status=${f.toLowerCase()}`}
            aria-current={f === filter ? "page" : undefined}
            className={`rounded-full border-2 px-4 py-1.5 font-bold ${f === filter ? "border-lagoon-bright bg-lagoon-soft text-lagoon" : "border-line bg-surface text-ink-soft"}`}
          >
            {FILTER_LABEL[f]} ({count(f)})
          </Link>
        ))}
      </nav>

      {skill.lessons.map((lesson) => {
        const shown = lesson.exercises.filter((e) => filter === "ALL" || e.status === filter);
        const approved = lesson.exercises.filter((e) => e.status === "APPROVED").length;
        return (
          <section key={lesson.id} className="space-y-3" aria-labelledby={`lesson-${lesson.id}`}>
            <div className="flex flex-wrap items-end justify-between gap-3">
              <div>
                <h2 id={`lesson-${lesson.id}`} className="font-display text-2xl">
                  Lesson {lesson.order}: {lesson.title}
                </h2>
                <p className="text-sm text-ink-soft">
                  {approved} approved exercise{approved === 1 ? "" : "s"}
                  {approved === 0 ? ". Learners can’t play this lesson until something is approved." : ""}
                </p>
              </div>
              <GenerateButton skillId={skill.id} lessonOrder={lesson.order} generatorName={generatorName} />
            </div>
            {shown.length === 0 ? (
              <p className="rounded-3xl border-2 border-dashed border-line p-5 text-ink-soft">
                No {filter === "ALL" ? "" : `${FILTER_LABEL[filter].toLowerCase()} `}exercises in this lesson.
              </p>
            ) : (
              <ol className="space-y-3">
                {shown.map((ex) => (
                  <ExerciseCard key={ex.id} ex={ex} />
                ))}
              </ol>
            )}
          </section>
        );
      })}
    </div>
  );
}
